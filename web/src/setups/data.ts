// The sheet writes each setting group as one dash-separated string ("41-1-1-21(5r)-20-40");
// here every value has its own field. `q` is the qualifying setup, `r` the race setup.

export type Generation = '2025' | '2026';

/** Qualifying and race values; identical when the sheet gives only one. */
export interface QualiRace<T> {
  q: T;
  r: T;
}

export interface Strategy {
  /** Tyre per stint, S/M/H, e.g. "MHH" is medium, then hard, then hard. */
  tyres: string;
  /** Pit-stop laps or windows, one per stop. */
  stops: string[];
  /** Best lap inside a one-stop window, when the sheet names one. */
  ideal?: number;
  /** Condition instead of laps, e.g. "if SC". */
  when?: string;
}

export interface TrackSetup {
  trackId: number;
  name: string;
  /** [front wing, rear wing] */
  wings: QualiRace<[number, number]>;
  /** [on-throttle %, off-throttle %] */
  diff: QualiRace<[number, number]>;
  /** [front suspension, rear suspension, front anti-roll bar, rear anti-roll bar, front ride height, rear ride height] */
  suspension: QualiRace<number[]>;
  brakePressure: QualiRace<number>;
  /** Front brake bias %, as a range when the sheet gives one. */
  brakeBias: number[];
  /** [front psi, rear psi] */
  tyrePressures: QualiRace<[number, number]>;
  /** C-numbers of the hard, medium and soft for this weekend. */
  compounds: number[];
  strategies: Strategy[];
  /** Race length the strategies are planned for (50% distance). */
  raceLaps: number;
  /** 2026 cars only: fuel load for a 50% race. */
  fuel?: string;
  /** 2026 cars only: ERS recharge limit in MJ. */
  recharge?: { q?: number | string; r?: number | string };
  note: string;
  /** Date it was driven, or "Theorycrafted" / "Theory" when it was not. */
  tested: string | null;
  /** The row exactly as the sheet writes it. */
  sheet: Record<string, string | number>;
}

